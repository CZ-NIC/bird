# Define aiocoap COAP Content-Format, these should get IANA preallocation soon
YANG_IDENTIFIERS_CF_ID = 65000
YANG_INSTANCES_CF_ID = 65001
_MT_YANG_IDENTIFIERS = ('application/yang-identifiers', 'cbor-seq')
_MT_YANG_INSTANCES = ('application/yang-instances', 'cbor-seq')

ContentFormat.define(
    YANG_IDENTIFIERS_CF_ID,
    media_type=_MT_YANG_IDENTIFIERS[0],
    encoding=_MT_YANG_IDENTIFIERS[1]
)
ContentFormat.define(
    YANG_INSTANCES_CF_ID,
    media_type=_MT_YANG_INSTANCES[0],
    encoding=_MT_YANG_INSTANCES[1]
)
YANG_IDS = ContentFormat.by_media_type(*_MT_YANG_IDENTIFIERS)
YANG_INST = ContentFormat.by_media_type(*_MT_YANG_INSTANCES)
YANG_DATA_SIDS = ContentFormat.by_media_type("application/yang-data+cbor; id=sid")

async def get_ctx():
    "Helper method"

    return await Context.create_client_context()

@dataclass
class Config:
    "Configuration data holding several URL for CORECONF+COAP"

    url: str
    datastore_url: str
    rpc_url: str
    event_stream_url: str
    yang_lib_url: str

class TestContentFormat:
    """Test correctness of used COAP Content-Formats by bird implementation of CORECONF.
    This should be soon generated by uytc."""

    @pytest.fixture(scope="class", autouse=True)
    @classmethod
    def urls(cls):
        url = "coap+tcp://localhost"
        datastore_url = url + "/c"
        rpc_url = url + "/c"
        event_stream_url = url + "/s"
        yang_lib_url = url + "/yl"

        bird = Path("../bird")
        birdc = Path("../birdc")
        if not bird.exists() or not birdc.exists():
            raise ValueError("Missing bird or birdc executable, please run this test inside the /yang subdirectory")

        try:
            cls.check_bird_health()
            cls.stop_bird()
        except ValueError:
            pass
             
        cls.start_bird()

        config = Config(url, datastore_url, rpc_url, event_stream_url, yang_lib_url)
        yield config

        cls.stop_bird()

    @classmethod
    def check_bird_health(cls):
        proc = subprocess.run(["../birdc", "-l", "status"])
        if not proc:
            raise ValueError("bird is not responsive")
        
    @classmethod
    def start_bird(cls):
        print("start bird")
        proc = subprocess.run(["../bird", "-c", "mini.conf", "-l"], capture_output=True)
        if proc.returncode != 0:
            raise ValueError("Failed to start bird")

    @classmethod
    def stop_bird(cls):
        print("stop bird")
        proc = subprocess.run(["../birdc", "-l", "down"])
        if proc.returncode != 0:
            raise ValueError("Failed to stop bird")

