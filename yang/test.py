    @pytest.mark.asyncio
    async def test_datastore_fetch_accept(self, urls):
        for acc in (0, YANG_IDS, YANG_DATA_SIDS):
            ctx = await get_ctx()
            req = Message(code=FETCH,
                          uri=urls.datastore_url,
                          content_format=YANG_IDS,
                          accept=acc)

            res = await ctx.request(req).response
            assert res.code == Code.NOT_ACCEPTABLE

        ctx = await get_ctx()
        req = Message(code=FETCH,
                      uri=urls.datastore_url,
                      content_format=YANG_IDS,
                      accept=YANG_INST)

        res = await ctx.request(req).response
        assert res.code != Code.NOT_ACCEPTABLE

